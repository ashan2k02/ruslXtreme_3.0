// Helper function to get scoped teams and relative ranks for a category
export function getLeaderboardForCategory(
  category: LeaderboardCategory
): (LeaderboardTeam & { displayRank: number })[] {
  const ruslTeams = demoLeaderboardTeams.filter((t) => t.isRajarata)

  return ruslTeams.map((team) => {
    let displayRank = team.universityRank ?? 1
    if (category === 'world') {
      displayRank = team.worldRank
    } else if (category === 'island') {
      displayRank = team.islandRank ?? team.worldRank
    } else {
      displayRank = team.universityRank ?? 1
    }

    return {
      ...team,
      displayRank,
    }
  })
}
