// Helper function to get scoped teams and relative ranks for a category
export function getLeaderboardForCategory(category: LeaderboardCategory): (LeaderboardTeam & { displayRank: number })[] {
  let filtered = [...demoLeaderboardTeams]
  if (category === 'island') {
    filtered = filtered.filter((t) => t.isSriLanka)
  } else if (category === 'university') {
    filtered = filtered.filter((t) => t.isRajarata)
  }

  // Sort by score DESC, then penalty ASC
  filtered.sort((a, b) => {
    if (b.score !== a.score) return b.score - a.score
    return a.penalty - b.penalty
  })

  return filtered.map((team, idx) => ({
    ...team,
    displayRank: idx + 1,
  }))
}
